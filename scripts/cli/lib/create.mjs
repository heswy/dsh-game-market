/**
 * `create-dsh-game` / `dsh-game init`: scaffold a runnable Game Market project
 * from `templates/<name>` (PRD §4.4 / §8.2.9).
 *
 * The generated project is self-describing: manifest source, template HTML,
 * game source, i18n, SDK typings, build/dev/validate/pack/publish wrappers and
 * a README. Wrappers call the local zero-dependency CLI; the CLI path is
 * recorded in `dsh-game.config.json` at creation time and can be overridden
 * with `DSH_GAME_CLI` (see the generated README).
 */

import fs from 'node:fs';
import path from 'node:path';

import { bundleExpression } from '../../bundle-lib.mjs';
import { GAME_ID_PATTERN } from '../../../packages/shared/src/constants.js';
import { RESERVED_GAME_IDS } from '../../../packages/shared/src/manifest.js';
import { usageError } from './cli-error.mjs';
import { dirExists, fileExists, listFilesRecursive, readText, toPosix, writeText } from './fs-utils.mjs';
import { REPO_ROOT, SDK_ENTRY, SDK_TYPES, TEMPLATES_ROOT, isInside } from './paths.mjs';

const TEMPLATE_NAMES = Object.freeze(['vanilla', 'react']);
const TEXT_EXTENSIONS = new Set(['.html', '.js', '.mjs', '.ts', '.tsx', '.css', '.md', '.json', '.gitignore', '.txt']);

function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}

function displayNameFromId(id) {
  return id
    .split('-')
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ');
}

function validateId(id) {
  if (typeof id !== 'string' || !GAME_ID_PATTERN.test(id)) {
    throw usageError(
      `Invalid game id "${id}"`,
      'Use 3–48 lowercase letters/digits/hyphens, starting and ending with an alphanumeric (e.g. my-game).'
    );
  }
  if (id.includes('--')) throw usageError('Game id must not contain "--".');
  if (RESERVED_GAME_IDS.includes(id)) throw usageError(`Game id "${id}" is reserved by DSH.`);
}

function replaceTokens(text, values, kind) {
  let output = text;
  if (kind === 'html') {
    output = output
      .replaceAll('__GAME_ID__', escapeHtml(values.id))
      .replaceAll('__GAME_TITLE__', escapeHtml(values.name))
      .replaceAll('__GAME_DESCRIPTION__', escapeHtml(values.description))
      .replaceAll('__GAME_AUTHOR__', escapeHtml(values.author));
  } else if (kind === 'code') {
    output = output
      .replaceAll('__GAME_TITLE_JSON__', JSON.stringify(values.name))
      .replaceAll('__GAME_ID_JSON__', JSON.stringify(values.id))
      .replaceAll('__GAME_DESCRIPTION_JSON__', JSON.stringify(values.description));
  } else {
    output = output
      .replaceAll('__GAME_ID__', values.id)
      .replaceAll('__GAME_TITLE__', values.name)
      .replaceAll('__GAME_DESCRIPTION__', values.description)
      .replaceAll('__GAME_AUTHOR__', values.author)
  }
  return output;
}

function manifestFor(values) {
  return {
    manifestVersion: 1,
    id: values.id,
    name: values.name,
    version: '1.0.0',
    author: { name: values.author },
    description: values.description,
    categories: ['arcade'],
    capabilities: ['storage', 'score'],
    sdkVersion: '^1.0.0',
    runtimeVersion: '^1.0.0',
    preferredTheme: 'game-defined',
    viewport: { width: 960, height: 540, fit: 'contain' },
    score: { direction: 'higher-better', min: 0, max: 1000000, integer: true },
    save: { schemaVersion: 1 },
  };
}

function packageJsonFor(template, values) {
  if (template === 'react') {
    const sourcePath = path.join(TEMPLATES_ROOT, 'react/package.json');
    const source = JSON.parse(readText(sourcePath));
    return {
      ...source,
      name: values.id,
      version: '1.0.0',
      private: true,
      description: values.description,
    };
  }
  return {
    name: values.id,
    version: '1.0.0',
    private: true,
    type: 'module',
    description: values.description,
    scripts: {
      build: 'node scripts/build.mjs',
      dev: 'node scripts/dev.mjs',
      validate: 'node scripts/validate.mjs',
      pack: 'node scripts/pack.mjs',
      publish: 'node scripts/publish.mjs',
    },
  };
}

let cachedSdkModule = null;

function sdkModuleSource() {
  if (cachedSdkModule === null) {
    const expression = bundleExpression({
      entry: toPosix(path.relative(REPO_ROOT, SDK_ENTRY)),
      root: REPO_ROOT,
    });
    cachedSdkModule = `// Generated by create-dsh-game from packages/sdk/src/sdk.js — do not edit by hand.
// Offline ESM wrapper around the zero-dependency Game SDK v1 bundle.
const __sdk = ${expression};

export const createGameSDK = __sdk.createGameSDK;
export const isGameError = __sdk.isGameError;
export const GameError = __sdk.GameError;
export const game = __sdk.game;
`;
  }
  return cachedSdkModule;
}

function configFor(template) {
  return {
    manifest: 'manifest.json',
    template: 'index.html',
    entry: template === 'react' ? 'src/main.tsx' : 'src/main.js',
    out: 'dist/index.html',
  };
}

/**
 * @param {{
 *   name: string, template?: 'vanilla'|'react', parentDir?: string,
 *   displayName?: string, description?: string, author?: string,
 *   force?: boolean, dryRun?: boolean
 * }} options
 */
export function createProject(options = {}) {
  const template = options.template || 'vanilla';
  if (!TEMPLATE_NAMES.includes(template)) {
    throw usageError(`Unknown template "${template}"`, `Available templates: ${TEMPLATE_NAMES.join(', ')}.`);
  }
  const id = String(options.name || '').trim();
  if (id.includes('/') || id.includes('\\') || id === '.' || id === '..') {
    throw usageError('Pass a bare game id (e.g. my-game) and use --dir to choose the parent directory.');
  }
  validateId(id);

  const parentDir = path.resolve(options.parentDir || process.cwd());
  // Resolve symlinks (macOS /tmp -> /private/tmp) so the recorded relative CLI
  // path stays valid when Node resolves the project through its real path.
  let realParent = parentDir;
  try {
    realParent = fs.realpathSync(parentDir);
  } catch (_error) {
    realParent = parentDir;
  }
  const targetDir = path.resolve(realParent, id);
  if (!isInside(REPO_ROOT, targetDir) && !isInside(realParent, targetDir)) {
    throw usageError('Refusing to create a project outside the requested parent directory.');
  }

  const templateDir = path.join(TEMPLATES_ROOT, template);
  if (!dirExists(templateDir)) throw usageError(`Template not found: ${toPosix(path.relative(REPO_ROOT, templateDir))}`);

  if (dirExists(targetDir) && !options.force) {
    const entries = fs.readdirSync(targetDir).filter((name) => name !== '.DS_Store');
    if (entries.length > 0) {
      throw usageError(`Directory is not empty: ${targetDir}`, 'Choose another name or pass --force to overwrite generated files.');
    }
  }
  if (fileExists(targetDir)) throw usageError(`Target exists and is a file: ${targetDir}`);

  let projectRoot = targetDir;
  if (!options.dryRun) {
    fs.mkdirSync(targetDir, { recursive: true });
    try {
      projectRoot = fs.realpathSync(targetDir);
    } catch (_error) {
      projectRoot = targetDir;
    }
  }
  const values = {
    id,
    name: options.displayName || displayNameFromId(id),
    description: options.description || `${displayNameFromId(id)} — a DSH Game Market game.`,
    author: options.author || 'Your Name',
  };

  if (options.dryRun) {
    return {
      ok: true,
      dryRun: true,
      id,
      template,
      targetDir: projectRoot,
      files: listFilesRecursive(templateDir).map((abs) => toPosix(path.relative(templateDir, abs))),
    };
  }

  const generated = [];
  const skip = new Set(['manifest.json', 'package.json', 'dsh-game.config.json']);
  for (const abs of listFilesRecursive(templateDir)) {
    const relative = toPosix(path.relative(templateDir, abs));
    if (skip.has(relative)) continue;
    const destination = path.join(targetDir, relative);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    const extension = path.extname(relative);
    if (relative.endsWith('.gitignore')) {
      writeText(destination, readText(abs));
    } else if (TEXT_EXTENSIONS.has(extension)) {
      const kind = extension === '.html' ? 'html' : ['.js', '.mjs', '.ts', '.tsx'].includes(extension) ? 'code' : 'text';
      writeText(destination, replaceTokens(readText(abs), values, kind));
    } else {
      fs.copyFileSync(abs, destination);
    }
    generated.push(relative);
  }

  const generatedFiles = {
    'manifest.json': `${JSON.stringify(manifestFor(values), null, 2)}\n`,
    'package.json': `${JSON.stringify(packageJsonFor(template, values), null, 2)}\n`,
    'dsh-game.config.json': `${JSON.stringify(configFor(template), null, 2)}\n`,
  };
  if (template === 'react') generatedFiles['vendor/dsh-game-sdk.js'] = sdkModuleSource();
  for (const [relative, content] of Object.entries(generatedFiles)) {
    writeText(path.join(targetDir, relative), content);
    generated.push(relative);
  }

  if (fileExists(SDK_TYPES)) {
    const sdkDir = path.join(targetDir, 'sdk');
    fs.mkdirSync(sdkDir, { recursive: true });
    fs.copyFileSync(SDK_TYPES, path.join(sdkDir, 'index.d.ts'));
    writeText(path.join(sdkDir, 'VERSION'), '1.0.0\n');
    generated.push('sdk/index.d.ts', 'sdk/VERSION');
  }

  return {
    ok: true,
    id,
    template,
    targetDir: projectRoot,
    name: values.name,
    description: values.description,
    author: values.author,
    files: [...new Set(generated)].sort(),
    nextSteps: [
      `cd ${targetDir}`,
      'export DSH_GAME_CLI=/path/to/dsh-game-market/scripts/cli/dsh-game.mjs',
      'npm run build',
      'npm run validate',
      template === 'react' ? 'npm install && npm run dev' : 'npm run dev',
      'npm run pack',
      'npm run publish -- --url https://github.com/<you>/<repo>/releases/download/v1.0.0/' + `${id}-1.0.0.html` + ' --cover https://example.com/cover.png',
    ],
  };
}

export { TEMPLATE_NAMES };
