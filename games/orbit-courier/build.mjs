#!/usr/bin/env node
/**
 * Build Orbit Courier as an `asset-zip-v2` package (contract §1, decision V1.5-01).
 *
 *   games/orbit-courier/dist/
 *     dsh-package.json   formatVersion 2, entry, gameManifest, files[]
 *     game.json          authoritative manifest (normalized copy of the source)
 *     index.html         entry document (external ESM/CSS only, no inline code)
 *     scripts/**         browser ESM modules + the bundled DSH game SDK
 *     styles/**          stylesheets
 *     assets/**          generated deterministic PNG sprites
 *     levels/**          level data loaded at runtime with a relative fetch
 *     audio/**           generated deterministic WAV one-shots
 *
 * Determinism: no timestamps, no absolute paths, sorted file list, fixed zlib
 * level for generated assets. Two builds of the same sources are byte-identical.
 *
 * The build imports the M1 shared validators read-only, so a green build means
 * the Host's archive pipeline would accept the same bytes.
 */

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

import { bundleExpression } from '../../scripts/bundle-lib.mjs';
import { validateManifest } from '../../packages/shared/src/manifest.js';
import {
  checkCssContent,
  checkHtmlContent,
  checkManifestConflict,
  checkPathConflicts,
  checkReservedNames,
  checkZipEntryPath,
  codePointCompare,
  fileManifestDigest,
  validateDescriptor,
} from '../../packages/shared/src/package-v2.js';
import { generateAssets } from './assets-src/generate.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
export const GAME_DIR = here;
export const DIST_DIR = path.join(here, 'dist');
export const DESCRIPTOR_FILE = 'dsh-package.json';
export const GAME_MANIFEST_FILE = 'game.json';
export const ENTRY_FILE = 'index.html';

const MANIFEST_FIELDS = [
  'manifestVersion',
  'id',
  'name',
  'version',
  'author',
  'description',
  'categories',
  'tags',
  'capabilities',
  'sdkVersion',
  'runtimeVersion',
  'preferredTheme',
  'viewport',
  'score',
  'save',
  'homepage',
  'repository',
  'license',
  'i18n',
];

function fail(message) {
  throw new Error(`[build:orbit-courier] ${message}`);
}

function readSourceManifest() {
  const file = path.join(here, GAME_MANIFEST_FILE);
  if (!fs.existsSync(file)) fail('missing games/orbit-courier/game.json');
  let manifest;
  try {
    manifest = JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (error) {
    fail(`game.json is not valid JSON: ${error.message}`);
  }
  const validation = validateManifest(manifest);
  if (!validation.ok) {
    fail(`game.json failed manifest validation:\n  ${validation.errors.map((error) => `${error.code}: ${error.message}`).join('\n  ')}`);
  }
  if (manifest.id !== 'orbit-courier') fail(`manifest id must be "orbit-courier", got ${manifest.id}`);
  return manifest;
}

/** Stable manifest text for the package copy (fixed field order, trailing newline). */
export function serializeManifest(manifest) {
  const ordered = {};
  for (const field of MANIFEST_FIELDS) {
    if (manifest[field] !== undefined) ordered[field] = manifest[field];
  }
  for (const key of Object.keys(manifest)) {
    if (!MANIFEST_FIELDS.includes(key)) ordered[key] = manifest[key];
  }
  return `${JSON.stringify(ordered, null, 2)}\n`;
}

/** Bundle the DSH game SDK into one ESM module inside the package (§1.10). */
function buildSdkModule() {
  const expression = bundleExpression({ entry: 'packages/sdk/src/sdk.js', root });
  return [
    '// Generated by games/orbit-courier/build.mjs — do not edit by hand.',
    '// The DSH Game SDK is bundled from packages/sdk/src (contract §1.10: one',
    '// manifest-listed SDK file inside an asset-zip-v2 package).',
    'const sdk = ' + expression + ';',
    'export const GameError = sdk.GameError;',
    'export const isGameError = sdk.isGameError;',
    'export const createGameSDK = sdk.createGameSDK;',
    'export const game = sdk.game;',
    '',
  ].join('\n');
}

function listFiles(directory, base = directory) {
  const out = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true }).sort((left, right) => codePointCompare(left.name, right.name))) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) out.push(...listFiles(absolute, base));
    else if (entry.isFile()) out.push(path.relative(base, absolute).split(path.sep).join('/'));
  }
  return out;
}

/**
 * Build the package in memory.
 * @returns {{files: Map<string, Buffer>, manifest: object, descriptor: object, digest: string}}
 */
export function buildPackage() {
  const manifest = readSourceManifest();
  const files = new Map();

  // 1. Entry document.
  const html = fs.readFileSync(path.join(here, 'src', 'index.html'), 'utf8');
  const htmlCheck = checkHtmlContent(html, { inlineForbidden: true });
  if (!htmlCheck.ok) fail(`index.html failed the inline/forbidden content scan: ${JSON.stringify(htmlCheck)}`);
  const conflict = checkManifestConflict(html);
  if (!conflict.ok) fail(`index.html carries a second inline manifest: ${JSON.stringify(conflict)}`);
  files.set(ENTRY_FILE, Buffer.from(html, 'utf8'));

  // 2. Stylesheets.
  const stylesDir = path.join(here, 'src', 'styles');
  for (const name of fs.readdirSync(stylesDir).sort(codePointCompare)) {
    if (!name.endsWith('.css')) continue;
    const css = fs.readFileSync(path.join(stylesDir, name), 'utf8');
    const cssCheck = checkCssContent(css);
    if (!cssCheck.ok) fail(`styles/${name} failed the CSS content scan: ${JSON.stringify(cssCheck)}`);
    files.set(`styles/${name}`, Buffer.from(css, 'utf8'));
  }

  // 3. Game ESM modules (verbatim) + the bundled SDK vendor module.
  const scriptsDir = path.join(here, 'src');
  for (const name of fs.readdirSync(scriptsDir).sort(codePointCompare)) {
    if (!name.endsWith('.js')) continue;
    files.set(`scripts/${name}`, fs.readFileSync(path.join(scriptsDir, name)));
  }
  files.set('scripts/vendor/dsh-sdk.js', Buffer.from(buildSdkModule(), 'utf8'));

  // 4. Level data.
  const levelsDir = path.join(here, 'src', 'levels');
  for (const name of fs.readdirSync(levelsDir).sort(codePointCompare)) {
    if (!name.endsWith('.json')) continue;
    files.set(`levels/${name}`, fs.readFileSync(path.join(levelsDir, name)));
  }

  // 5. Generated sprites and one-shots.
  for (const [relative, buffer] of generateAssets()) {
    files.set(relative, buffer);
  }

  // 6. Authoritative manifest copy.
  files.set(GAME_MANIFEST_FILE, Buffer.from(serializeManifest(manifest), 'utf8'));

  // 7. Descriptor: sorted file list, descriptor itself excluded (§1.4).
  const paths = [...files.keys()].sort(codePointCompare);
  const fileEntries = paths.map((relative) => ({
    path: relative,
    size: files.get(relative).length,
    sha256: crypto.createHash('sha256').update(files.get(relative)).digest('hex'),
  }));
  const descriptor = {
    formatVersion: 2,
    entry: ENTRY_FILE,
    gameManifest: GAME_MANIFEST_FILE,
    files: fileEntries,
  };

  // 8. Validate with the M1 shared validators before anything is written.
  const descriptorResult = validateDescriptor(descriptor);
  if (!descriptorResult.ok) fail(`descriptor failed validation: ${JSON.stringify(descriptorResult)}`);
  for (const relative of paths) {
    const entryCheck = checkZipEntryPath(relative);
    if (!entryCheck.ok) fail(`archive path rejected: ${relative} — ${JSON.stringify(entryCheck)}`);
  }
  const conflicts = checkPathConflicts(paths);
  if (!conflicts.ok) fail(`archive path conflict: ${JSON.stringify(conflicts)}`);
  const reserved = checkReservedNames(paths);
  if (!reserved.ok) fail(`reserved file name in package root: ${JSON.stringify(reserved)}`);
  const sha256Hex = (text) => crypto.createHash('sha256').update(text, 'utf8').digest('hex');
  const digest = fileManifestDigest(descriptorResult.value.files, sha256Hex);
  if (!/^[a-f0-9]{64}$/.test(digest)) fail('file manifest digest is not a sha256 hex string');

  return { files, manifest, descriptor, digest };
}

/** Write the built package to games/orbit-courier/dist and return a summary. */
export function writeBuild() {
  const built = buildPackage();
  fs.rmSync(DIST_DIR, { recursive: true, force: true });
  fs.mkdirSync(DIST_DIR, { recursive: true });
  const paths = [...built.files.keys()].sort(codePointCompare);
  for (const relative of paths) {
    const target = path.join(DIST_DIR, relative);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, built.files.get(relative));
  }
  const descriptorText = `${JSON.stringify(built.descriptor, null, 2)}\n`;
  fs.writeFileSync(path.join(DIST_DIR, DESCRIPTOR_FILE), descriptorText, 'utf8');
  const totalBytes = paths.reduce((sum, relative) => sum + built.files.get(relative).length, 0);
  return {
    ...built,
    distDir: DIST_DIR,
    fileCount: paths.length + 1,
    packageBytes: totalBytes,
    descriptorSha256: crypto.createHash('sha256').update(descriptorText).digest('hex'),
  };
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  try {
    const result = writeBuild();
    console.log(
      `[build:orbit-courier] ${result.manifest.id}@${result.manifest.version} · ${result.manifest.categories.join(',')} · ` +
        `${result.manifest.capabilities.join('+')} · viewport ${result.manifest.viewport.width}x${result.manifest.viewport.height}`,
    );
    console.log(`[build:orbit-courier] asset-zip-v2: ${result.fileCount} entries (incl. descriptor), ${result.packageBytes} bytes unpacked`);
    for (const file of result.descriptor.files) {
      console.log(`[build:orbit-courier]   ${file.path} (${file.size} B, ${file.sha256.slice(0, 12)}…)`);
    }
    console.log(`[build:orbit-courier] fileManifestDigest ${result.digest}`);
    console.log(`[build:orbit-courier] descriptor sha256 ${result.descriptorSha256}`);
  } catch (error) {
    console.error(error && error.message ? error.message : error);
    process.exit(1);
  }
}
